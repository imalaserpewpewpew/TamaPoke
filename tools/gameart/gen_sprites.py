OUT=(0x1b,0x1b,0x25)
def life_icon():
    # little astromech dome: lit metal half-sphere, red eye, blue panel, dark rim
    N=14; im=Image.new('RGBA',(N,10),(0,0,0,0)); p=im.load()
    c=(N-1)/2; R=6.4
    for y in range(10):
        for x in range(N):
            dx=(x-c)/R; dy=(y-8.0)/R
            if dy>0 or dx*dx+dy*dy>1: continue
            nz=math.sqrt(max(0,1-dx*dx-dy*dy)); diff=max(0,-0.55*dx-0.65*dy+0.52*nz)
            v=int(120+110*diff); p[x,y]=(v,v+4,v+14,255)
    for x in range(1,N-1): p[x,8]=(60,64,76,255)          # rim
    for (x,y) in ((6,4),(7,4),(6,5),(7,5)): p[x,y]=(230,60,50,255)   # eye
    for (x,y) in ((9,5),(10,5),(9,6),(10,6),(3,6),(4,6)): p[x,y]=(70,120,200,255)
    q=im.copy().load()
    for y in range(10):
        for x in range(N):
            if q[x,y][3]: continue
            if any(0<=x+a<N and 0<=y+b<10 and q[x+a,y+b][3] for a,b in ((1,0),(-1,0),(0,1),(0,-1))): p[x,y]=OUT+(255,)
    return im
def rgb565(c): return ((c[0]&0xF8)<<8)|((c[1]&0xFC)<<3)|(c[2]>>3)
def emit(name,im,maxc=48):
    rgb=im.convert('RGB'); a=im.split()[3]
    q=rgb.quantize(colors=maxc,method=Image.MEDIANCUT); pal=q.getpalette()
    used=sorted(set(q.getdata()))
    remap={u:i for i,u in enumerate(used)}
    w,h=im.size; idx=[]
    for y in range(h):
        for x in range(w):
            idx.append(255 if a.getpixel((x,y))<128 else remap[q.getpixel((x,y))])
    cols=[rgb565(tuple(pal[u*3:u*3+3])) for u in used]
    s=f'static const uint16_t {name}_PAL[{len(cols)}] = {{'+','.join(f'0x{c:04X}' for c in cols)+'};\n'
    s+=f'static const uint8_t {name}_IDX[{w*h}] = {{\n'
    for i in range(0,len(idx),w): s+='  '+','.join(str(v) for v in idx[i:i+w])+',\n'
    s+='};\n'
    s+=f'static const IdxSprite {name} = {{ {w}, {h}, {name}_PAL, {name}_IDX }};\n\n'
    return s
